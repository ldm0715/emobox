/**
 * 分组自定义图标的注册表 —— 图标名（SQLite `groups.icon` 存的值）的白名单事实源。
 * 新增图标：在这里加 `*24Regular` 导入 + 对应 entry 即可，`getGroupIcon` 对
 * 未知名一律回退默认文件夹图标。
 */

export interface GroupIconEntry {
  /** 稳定标识，直接存 SQLite `groups.icon` 列。 */
  name: string;
  component: ComponentType<{ className?: string }>;
  /** 中文显示名。 */
  label: string;
  /** 搜索关键词（含英文名的小写形式）。 */
  keywords: string[];
}

export interface GroupIconCategory {
  label: string;
  icons: GroupIconEntry[];
}

function entry(
  name: string,
  component: ComponentType<{ className?: string }>,
  label: string,
  ...keywords: string[]
): GroupIconEntry {
  return { name, component, label, keywords: [name.toLowerCase(), label, ...keywords] };
}

