const ICON_INDEX: Map<string, GroupIconEntry> = (() => {
  const map = new Map<string, GroupIconEntry>();
  for (const category of GROUP_ICON_CATEGORIES) {
    for (const icon of category.icons) {
      map.set(icon.name, icon);
    }
  }
  return map;
})();

/** 按注册名取图标组件；null / 未知名一律回退默认文件夹图标。 */
export function getGroupIcon(name: string | null): ComponentType<{ className?: string }> {
  if (name) return ICON_INDEX.get(name)?.component ?? Folder24Regular;
  return Folder24Regular;
}

/** 按注册名取完整 entry（含中文 label），未知名返回 undefined。 */
export function findGroupIconEntry(name: string): GroupIconEntry | undefined {
  return ICON_INDEX.get(name);
}

