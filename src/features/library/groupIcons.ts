/** 按关键词过滤分类（英文小写 / 中文 label / keywords 子串匹配）。 */
export function searchGroupIcons(query: string): GroupIconCategory[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return GROUP_ICON_CATEGORIES;
  return GROUP_ICON_CATEGORIES.map((category) => ({
    label: category.label,
    icons: category.icons.filter((icon) => icon.keywords.some((keyword) => keyword.toLowerCase().includes(trimmed))),
  })).filter((category) => category.icons.length > 0);
}
